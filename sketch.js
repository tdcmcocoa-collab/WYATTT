// ==========================================

function showPage(pageID) {
  const pages =
    document.querySelectorAll(".page");

  pages.forEach(page => {
    page.style.display = "none";
  });

  const page =
    document.getElementById(pageID);

  if (page) {
    page.style.display = "block";
  }

  window.scrollTo(0, 0);
}

function goHome() {
  showPage("home-page");
}

function goGames() {
  showPage("games-page");
}

// ==========================================
// HOME SEARCH
// ==========================================

function searchFromHome() {
  const query = homeSearch
    .value()
    .toLowerCase()
    .trim();

  showPage("games-page");

  if (query === "") {
    gameSearch.value("");

    currentGames = games;
    displayedAmount = GAMES_PER_LOAD;

    displayGames();
    return;
  }

  gameSearch.value(query);

  currentGames = games.filter(game =>
    game.name.toLowerCase().includes(query) ||
    game.slug.toLowerCase().includes(query)
  );

  displayedAmount = GAMES_PER_LOAD;

  displayGames();
}

// ==========================================
// GAME SEARCH
// ==========================================

function filterGames() {
  const query = gameSearch
    .value()
    .toLowerCase()
    .trim();

  if (query === "") {
    currentGames = games;
  } else {
    currentGames = games.filter(game =>
      game.name.toLowerCase().includes(query) ||
      game.slug.toLowerCase().includes(query)
    );
  }

  displayedAmount = GAMES_PER_LOAD;

  displayGames();
}

// ==========================================
// DISPLAY GAMES
// ==========================================

function displayGames() {
  gameContainer.html("");

  const visibleGames =
    currentGames.slice(0, displayedAmount);

  visibleGames.forEach(game => {
    const card =
      document.createElement("div");

    card.className = "game-card";

    const name =
      document.createElement("div");

    name.className = "game-name";
    name.innerText = game.name;

    card.appendChild(name);

    card.addEventListener(
      "click",
      function() {
        openGame(game);
      }
    );

    gameContainer.elt.appendChild(card);
  });

  const countElement =
    document.getElementById("game-count");

  if (countElement) {
    if (currentGames.length === games.length) {
      countElement.innerText =
        `${games.length} GAMES`;
    } else {
      countElement.innerText =
        `${currentGames.length} RESULTS`;
    }
  }

  if (loadMoreButton) {
    if (
      displayedAmount >=
      currentGames.length
    ) {
      loadMoreButton.style.display =
        "none";
    } else {
      loadMoreButton.style.display =
        "block";
    }
  }
}
