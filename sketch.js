function createWelcomeScreen() {
  const welcome = document.createElement("div");
  welcome.id = "welcome-screen";

  const box = document.createElement("div");
  box.className = "welcome-box";

  const title = document.createElement("h1");
  title.id = "welcome-title";
  title.innerText = "Welcome to Wyatt!";

  const text = document.createElement("p");
  text.id = "welcome-text";
  text.innerText = "";

  // ---------- COLOR PICKER ----------

  const colorSection = document.createElement("div");
  colorSection.id = "welcome-color-section";

  const colorTitle = document.createElement("h2");
  colorTitle.id = "welcome-color-title";
  colorTitle.innerText = "Before you go, pick a color";

  const colorOptions = document.createElement("div");
  colorOptions.id = "welcome-color-options";

  const colors = [
    { name: "Blue", color: "#3b82f6" },
    { name: "Dark Blue", color: "#2563eb" },
    { name: "Cyan", color: "#06b6d4" },
    { name: "Pink", color: "#ec4899" },
    { name: "Purple", color: "#8b5cf6" },
    { name: "Green", color: "#22c55e" },
    { name: "Red", color: "#ef4444" }
  ];

  colors.forEach((item, index) => {
    const colorButton = document.createElement("button");

    colorButton.className = "welcome-color";
    colorButton.style.setProperty("--picker-color", item.color);
    colorButton.setAttribute("aria-label", item.name);
    colorButton.title = item.name;

    if (index === 0) {
      colorButton.classList.add("selected");
    }

    colorButton.addEventListener("click", function() {
      document.querySelectorAll(".welcome-color").forEach(button => {
        button.classList.remove("selected");
      });

      colorButton.classList.add("selected");

      setWyattColor(item.color);
    });

    colorOptions.appendChild(colorButton);
  });

  colorSection.appendChild(colorTitle);
  colorSection.appendChild(colorOptions);

  // ---------- NEXT BUTTON ----------

  const nextButton = document.createElement("button");
  nextButton.id = "welcome-next";
  nextButton.innerText = "NEXT →";

  const progress = document.createElement("div");
  progress.id = "welcome-progress";

  box.appendChild(title);
  box.appendChild(text);
  box.appendChild(colorSection);
  box.appendChild(nextButton);
  box.appendChild(progress);

  welcome.appendChild(box);
  document.body.appendChild(welcome);

  let step = 0;

  function updateWelcome() {
    if (step === 0) {
      title.innerText = "Welcome to Wyatt!";
      text.innerText = "Your place for games, movies, and fun.";
      colorSection.style.display = "none";
      nextButton.innerText = "NEXT →";
    }

    if (step === 1) {
      title.innerText = "We have 458 games";
      text.innerText =
        "Plus movies whenever you want to watch something.";
      colorSection.style.display = "block";
      nextButton.innerText = "NEXT →";
    }

    if (step === 2) {
      title.innerText = "Updates will come soon";
      text.innerText =
        "We're always working on making Wyatt better.";
      colorSection.style.display = "block";
      nextButton.innerText = "GO TO WEBSITE →";
    }

    progress.innerText = `${step + 1} / 3`;
  }

  nextButton.addEventListener("click", function() {
    if (step < 2) {
      step++;
      updateWelcome();
    } else {
      welcome.classList.add("welcome-hidden");

      setTimeout(() => {
        welcome.remove();
      }, 400);
    }
  });

  updateWelcome();

  setWyattColor("#3b82f6");
}

