// ==========================================
// LOAD PRIVATE SUGGESTIONS
// ==========================================

async function loadPrivateSuggestions() {
  if (
    SUPABASE_URL ===
      "YOUR_SUPABASE_URL" ||
    SUPABASE_ANON_KEY ===
      "YOUR_SUPABASE_ANON_KEY"
  ) {
    privateSuggestionsContainer.innerHTML =
      `
        <div class="private-suggestions-empty">
          <h2>Database not connected</h2>
          <p>
            Add your Supabase URL and public anon key
            near the top of the code.
          </p>
        </div>
      `;

    return;
  }

  try {
    const response =
      await fetch(
        `${SUPABASE_URL}/rest/v1/suggestions?select=id,suggestion,created_at&order=created_at.desc`,
        {
          method: "GET",

          headers: {
            "apikey":
              SUPABASE_ANON_KEY,

            "Authorization":
              `Bearer ${SUPABASE_ANON_KEY}`
          }
        }
      );

    if (!response.ok) {
      throw new Error(
        "Unable to load suggestions."
      );
    }

    const suggestions =
      await response.json();

    privateSuggestionsContainer.innerHTML =
      "";

    if (
      !suggestions ||
      suggestions.length === 0
    ) {
      const empty =
        document.createElement("div");

      empty.className =
        "private-suggestions-empty";

      empty.innerText =
        "No suggestions yet.";

      privateSuggestionsContainer.appendChild(
        empty
      );

      return;
    }

    suggestions.forEach(
      function(item) {
        createSuggestionCard(item);
      }
    );
  } catch (error) {
    console.error(
      "Private suggestions error:",
      error
    );

    privateSuggestionsContainer.innerHTML =
      `
        <div class="private-suggestions-empty">
          <h2>Could not load suggestions</h2>
          <p>
            Check your database connection and permissions.
          </p>
        </div>
      `;
  }
}

// ==========================================
// SUGGESTION CARD
// ==========================================

function createSuggestionCard(item) {
  const card =
    document.createElement("div");

  card.className =
    "private-suggestion-card";

  const suggestion =
    document.createElement("div");

  suggestion.className =
    "private-suggestion-text";

  suggestion.innerText =
    item.suggestion;

  const date =
    document.createElement("div");

  date.className =
    "private-suggestion-date";

  if (item.created_at) {
    const parsedDate =
      new Date(item.created_at);

    if (
      !Number.isNaN(
        parsedDate.getTime()
      )
    ) {
      date.innerText =
        parsedDate.toLocaleString();
    }
  }

  card.appendChild(suggestion);
  card.appendChild(date);

  privateSuggestionsContainer.appendChild(
    card
  );
}

