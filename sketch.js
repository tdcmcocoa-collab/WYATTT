// ==========================================
// SUPABASE DATABASE
// ==========================================

async function submitSuggestion() {
  const suggestion =
    suggestionInput.value.trim();

  if (!suggestion) {
    suggestionStatus.innerText =
      "Please type a suggestion first.";

    suggestionStatus.className =
      "suggestion-error";

    return;
  }

  if (suggestion.length > 500) {
    suggestionStatus.innerText =
      "Your suggestion is too long.";

    suggestionStatus.className =
      "suggestion-error";

    return;
  }

  if (
    SUPABASE_URL ===
      "YOUR_SUPABASE_URL" ||
    SUPABASE_ANON_KEY ===
      "YOUR_SUPABASE_ANON_KEY"
  ) {
    suggestionStatus.innerText =
      "The suggestion system has not been connected yet.";

    suggestionStatus.className =
      "suggestion-error";

    return;
  }

  suggestionStatus.innerText =
    "Sending...";

  suggestionStatus.className =
    "suggestion-loading";

  try {
    const response =
      await fetch(
        `${SUPABASE_URL}/rest/v1/suggestions`,
        {
          method: "POST",

          headers: {
            "Content-Type":
              "application/json",

            "apikey":
              SUPABASE_ANON_KEY,

            "Authorization":
              `Bearer ${SUPABASE_ANON_KEY}`,

            "Prefer":
              "return=minimal"
          },

          body: JSON.stringify({
            suggestion: suggestion
          })
        }
      );

    if (!response.ok) {
      let errorMessage =
        "Could not send suggestion.";

      try {
        const errorData =
          await response.json();

        if (
          errorData &&
          errorData.message
        ) {
          errorMessage =
            errorData.message;
        }
      } catch (error) {
        // Ignore JSON parsing errors.
      }

      throw new Error(
        errorMessage
      );
    }

    suggestionInput.value = "";

    suggestionStatus.innerText =
      "Suggestion sent! Thank you.";

    suggestionStatus.className =
      "suggestion-success";
  } catch (error) {
    console.error(
      "Suggestion error:",
      error
    );

    suggestionStatus.innerText =
      "Something went wrong. Please try again.";

    suggestionStatus.className =
      "suggestion-error";
  }
}

